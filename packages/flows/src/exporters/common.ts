import type { ExportOptions, Flow, FlowStep } from '../schema.js';

/** A double-quoted string literal that is valid in TypeScript, Python and Java. */
export const q = (s: string): string => JSON.stringify(s);

export const cssEscapeId = (id: string): string => id.replace(/([^a-zA-Z0-9_-])/g, '\\$1');

/** Path part of a frame address, used as `iframe[src*="..."]`. */
export function frameMatch(url: string): string {
  try {
    const u = new URL(url);
    return u.pathname.length > 1 ? u.pathname : u.host;
  } catch {
    return url.slice(0, 60);
  }
}

export function defaultsOf(flow: Flow, opts?: ExportOptions): Record<string, string> {
  const out: Record<string, string> = {};
  if (opts?.includeDefaults) for (const p of flow.params) if (!p.sensitive && p.default !== undefined) out[p.name] = p.default;
  return out;
}

/**
 * Text that is safe inside a one-line `//` or `#` comment: line breaks and other control or separator characters become spaces, so
 * recorded names and labels cannot end the comment and become code. Two languages read comments before parsing code: Java decodes
 * `\uXXXX` everywhere, so the backslash of `\u` is split off; Python takes `coding:` / `coding=` in the first two lines as the file's
 * encoding (PEP 263; `unicode_escape` would turn `\x0a` into a line break), so the word is split from its `:` or `=`.
 */
export const oneLine = (s: string): string =>
  s
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u001f\u007f-\u009f\u2028\u2029]+/g, ' ')
    .replace(/\\(?=u)/gi, '\\ ')
    .replace(/(coding)(?=[:=])/gi, '$1 ');

export function header(flow: Flow, comment: string): string {
  const consequential = flow.steps.filter((s) => s.consequential).length;
  return [
    `Generated by BrowserForge from the "${flow.name}" flow for ${flow.site} (${flow.steps.length} steps).`,
    `Parameters: ${flow.params.length ? flow.params.map((p) => p.name + (p.sensitive ? ' (sensitive: supply it yourself)' : '')).join(', ') : 'none'}.`,
    consequential
      ? `${consequential} step(s) are consequential (submit, send, upload, password). Outside BrowserForge there is no approval prompt, so the script stops before them unless FLOW_CONFIRM=1.`
      : 'No consequential steps.',
  ].map((l) => `${comment} ${oneLine(l)}`).join('\n');
}

export const stepLabel = (s: FlowStep, i: number): string => oneLine(`step ${i + 1}: ${s.label ?? s.action}`);

/** Selenium and Chrome Recorder cannot address an element inside an open shadow root; Playwright's CSS pierces it. Refuse rather than write a script that cannot find the element. */
export function refuseShadow(flow: Flow, format: string): void {
  const i = flow.steps.findIndex((s) => s.locator?.shadow?.length);
  if (i >= 0) throw new Error(`Step ${i + 1} is inside an open shadow root, which the ${format} format cannot address. Export playwright-ts or playwright-py instead: their CSS locators reach into open shadow DOM.`);
}
