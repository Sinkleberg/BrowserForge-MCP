import type { IrOp } from './ir.js';
import { ident, type Lang } from './naming.js';

export interface NamedParam { wire: string; local: string; type: string }

/** Local identifiers for an operation's parameters, de-duplicated across path/query. */
export function paramNames(op: IrOp, lang: Lang): { path: NamedParam[]; query: NamedParam[] } {
  const seen = new Set<string>();
  const uniq = (base: string) => { let n = base, i = 2; while (seen.has(n)) n = `${base}${lang === 'python' ? '_' : ''}${i++}`; seen.add(n); return n; };
  const path = op.pathParams.map((p) => ({ wire: p.wire, local: uniq(ident(p.wire, lang)), type: p.type }));
  const query = op.query.map((p) => ({ wire: p.wire, local: uniq(ident(p.wire, lang)), type: p.type }));
  return { path, query };
}

export const strLit = (s: string): string => JSON.stringify(s);
/** PHP single-quoted literal (no interpolation). */
export const phpLit = (s: string): string => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

