import { z } from 'zod';

export const PROTOCOL_VERSION = 1;

export const ERROR_CODES = [
  'INVALID_ARGUMENTS', 'UNAUTHORIZED', 'NOT_CONNECTED', 'TIMEOUT', 'CANCELLED', 'TAB_NOT_FOUND',
  'ELEMENT_NOT_FOUND', 'ELEMENT_DISABLED', 'STALE_REF', 'NAVIGATION_FAILED', 'APPROVAL_REQUIRED', 'APPROVAL_DENIED', 'PAUSED',
  'STOPPED', 'UNSUPPORTED', 'PERMISSION_DENIED', 'PATH_NOT_ALLOWED', 'NOT_FOUND', 'LIMIT_EXCEEDED',
  'GENERATION_FAILED', 'INTERNAL',
] as const;

const requestId = z.string().min(1).max(100);

export const ProtocolErrorSchema = z.object({
  code: z.enum(ERROR_CODES),
  message: z.string().max(2000),
  retryable: z.boolean().default(false),
  details: z.record(z.string(), z.unknown()).optional(),
});
export type ProtocolError = z.infer<typeof ProtocolErrorSchema>;

/** Server → extension: perform an action. */
export const RequestSchema = z.object({
  v: z.literal(PROTOCOL_VERSION),
  type: z.literal('request'),
  id: requestId,
  action: z.string().min(1).max(64),
  args: z.record(z.string(), z.unknown()).default({}),
  /** Soft deadline the extension should respect; the server enforces the hard one. */
  timeoutMs: z.number().int().positive().max(600_000).optional(),
});
export type Request = z.infer<typeof RequestSchema>;

/** Extension → server: result of a request. */
export const ResponseSchema = z.discriminatedUnion('ok', [
  z.object({ v: z.literal(PROTOCOL_VERSION), type: z.literal('response'), id: requestId, ok: z.literal(true), result: z.unknown() }),
  z.object({ v: z.literal(PROTOCOL_VERSION), type: z.literal('response'), id: requestId, ok: z.literal(false), error: ProtocolErrorSchema }),
]);
export type Response = z.infer<typeof ResponseSchema>;

/** Server → extension: abandon a request. */
export const CancelSchema = z.object({ v: z.literal(PROTOCOL_VERSION), type: z.literal('cancel'), id: requestId });

export const CapabilitiesSchema = z.object({
  networkCapture: z.boolean(),
  responseBodies: z.boolean(),
  webSocketFrames: z.boolean(),
  screenshots: z.boolean(),
  fullPageScreenshots: z.boolean(),
  downloads: z.boolean(),
});
export type Capabilities = z.infer<typeof CapabilitiesSchema>;

/** Extension → server: first message on a connection; carries the shared secret. */
export const HelloSchema = z.object({
  v: z.literal(PROTOCOL_VERSION),
  type: z.literal('hello'),
  token: z.string().min(16).max(200),
  browser: z.object({
    kind: z.enum(['firefox', 'chrome']),
    version: z.string().max(50),
    /** Stable per-profile id generated by the extension; used for reconnect/resume. */
    id: z.string().min(8).max(100),
  }),
  extension: z.object({ id: z.string().max(100), version: z.string().max(30) }),
  capabilities: CapabilitiesSchema,
});
export type Hello = z.infer<typeof HelloSchema>;

export const HelloAckSchema = z.object({
  v: z.literal(PROTOCOL_VERSION),
  type: z.literal('hello_ack'),
  serverVersion: z.string(),
  sessionId: z.string(),
});

/** Captured HTTP exchange pushed by the extension (see network-inspector for the stored shape). */
export const NetworkEventSchema = z.object({
  v: z.literal(PROTOCOL_VERSION),
  type: z.literal('event'),
  event: z.literal('network'),
  data: z.object({
    requestId: z.string().max(200),
    tabId: z.number().int(),
    url: z.string().max(8000),
    method: z.string().max(16),
    requestHeaders: z.array(z.object({ name: z.string(), value: z.string() })).default([]),
    requestBody: z.string().max(2_000_000).optional(),
    requestBodyTruncated: z.boolean().optional(),
    status: z.number().int().optional(),
    statusText: z.string().optional(),
    responseHeaders: z.array(z.object({ name: z.string(), value: z.string() })).default([]),
    responseBody: z.string().max(2_000_000).optional(),
    responseBodyBase64: z.boolean().optional(),
    responseBodyTruncated: z.boolean().optional(),
    mimeType: z.string().optional(),
    resourceType: z.string().optional(),
    initiator: z.string().max(2000).optional(),
    startedAt: z.number(),
    endedAt: z.number().optional(),
    fromCache: z.boolean().optional(),
    error: z.string().max(500).optional(),
  }),
});
export type NetworkEvent = z.infer<typeof NetworkEventSchema>;

export const ActivityEventSchema = z.object({
  v: z.literal(PROTOCOL_VERSION),
  type: z.literal('event'),
  event: z.literal('activity'),
  data: z.object({ at: z.number(), action: z.string().max(64), summary: z.string().max(300), tabId: z.number().int().optional(), outcome: z.enum(['ok', 'error', 'pending', 'denied']) }),
});

/**
 * Something the PERSON did in the browser (not an agent), sent only while "Record me" is on. It describes the element and the page
 * (control rows without refs), never a value unless the person turned "Store my values" on, and never for password-like fields.
 */
export const HumanActionEventSchema = z.object({
  v: z.literal(PROTOCOL_VERSION),
  type: z.literal('event'),
  event: z.literal('human'),
  data: z.object({
    at: z.number(),
    tabId: z.number().int().optional(),
    kind: z.enum(['click', 'fill', 'select', 'press', 'upload']),
    url: z.string().max(4000),
    frameUrl: z.string().max(4000).optional(),
    locator: z.record(z.string().max(30), z.string().max(600)).optional(),
    /** Which of several equal matches the element is (0-based), and the CSS of the open shadow hosts around it, outermost first. */
    nth: z.number().int().min(0).max(10000).optional(),
    shadow: z.array(z.string().max(600)).max(8).optional(),
    /** A click on a checkbox or radio: the state it left the control in. */
    state: z.enum(['checked', 'unchecked']).optional(),
    fieldLabel: z.string().max(120).optional(),
    value: z.string().max(5000).optional(),
    key: z.string().max(30).optional(),
    sensitive: z.boolean().optional(),
    consequential: z.boolean().optional(),
    custom: z.boolean().optional(),
    /** 1-based position of the touched control in `table`. */
    row: z.number().int().positive().max(1000).optional(),
    /** The page's control rows just before the action: "n | kind | label" (no refs). */
    table: z.array(z.string().max(200)).max(120).optional(),
    /** What the person said they are doing, if they said. */
    task: z.string().max(200).optional(),
  }),
});
export type HumanActionEvent = z.infer<typeof HumanActionEventSchema>;

/**
 * The person pressed "Ask the agent" in the popup: a request for whichever agent is connected to work on this page. The URL and title are
 * page data (untrusted); the note is what the person typed.
 */
export const AskAgentEventSchema = z.object({
  v: z.literal(PROTOCOL_VERSION),
  type: z.literal('event'),
  event: z.literal('ask'),
  data: z.object({
    at: z.number(),
    tabId: z.number().int(),
    url: z.string().max(4000),
    title: z.string().max(300).optional(),
    note: z.string().max(500).optional(),
  }),
});
export type AskAgentEvent = z.infer<typeof AskAgentEventSchema>;

export const PingSchema = z.object({ v: z.literal(PROTOCOL_VERSION), type: z.enum(['ping', 'pong']) });

/** Everything the server accepts from an (authenticated) extension connection. */
export const ExtensionMessageSchema = z.union([ResponseSchema, NetworkEventSchema, ActivityEventSchema, HumanActionEventSchema, AskAgentEventSchema, PingSchema]);
export type ExtensionMessage = z.infer<typeof ExtensionMessageSchema>;

export function errorResponse(id: string, error: Omit<ProtocolError, 'retryable'> & { retryable?: boolean }): Response {
  return { v: PROTOCOL_VERSION, type: 'response', id, ok: false, error: { retryable: false, ...error } };
}
export function okResponse(id: string, result: unknown): Response {
  return { v: PROTOCOL_VERSION, type: 'response', id, ok: true, result };
}
